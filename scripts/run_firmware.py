"""Stage 4c: the int8 C kernel, checked against the NumPy reference and sized
for a Cortex-M4.

For each leave-one-load-out fold:
1. quantise the seed-0 CNN (isense.int8), calibrated on 256 training windows
2. write firmware/wdcnn_weights.h
3. build firmware/ for the PC, run it on the held-out windows, and require
   its logits to equal the NumPy reference bit for bit
Then build the fold-0 kernel for a Cortex-M4 and record flash, static RAM and
stack. Nothing here runs on a board; the M4 numbers are from the linker and
from GCC's stack-usage report.

Compilers: CC (default gcc) for the PC, ARM_CC (default arm-none-eabi-gcc).
Usage: python scripts/run_firmware.py   (needs run_cnn.py first; writes results/firmware.json)
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import numpy as np
import torch
from sklearn.metrics import f1_score

ROOT = Path(__file__).resolve().parents[1]
FW = ROOT / "firmware"
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))

from isense import cnn, int8  # noqa: E402
from run_cnn import build  # noqa: E402

CFLAGS = ["-std=c99", "-O2", "-ffp-contract=off", "-Wall", "-Wextra", "-Werror"]
M4FLAGS = ["-mcpu=cortex-m4", "-mthumb", "-mfpu=fpv4-sp-d16", "-mfloat-abi=hard", "-Os", "-std=c99",
           "-ffp-contract=off", "-ffunction-sections", "-fdata-sections", "-fstack-usage", "-Wall", "-Werror"]


def c_array(ctype: str, name: str, a: np.ndarray, fmt) -> str:
    vals = ", ".join(fmt(v) for v in a.ravel())
    return f"static const {ctype} {name}[{a.size}] = {{{vals}}};\n"


def write_header(q: int8.QModel, path: Path):
    f32 = lambda v: f"{float(np.float32(v))!r}f".replace("inff", "INFINITY")  # noqa: E731
    out = ["/* Generated by scripts/run_firmware.py. Do not edit. */\n",
           "#ifndef WDCNN_WEIGHTS_H\n#define WDCNN_WEIGHTS_H\n#include <stdint.h>\n",
           f"#define WD_IN_SCALE {f32(q.in_scale)}\n"]
    for i, c in enumerate(q.convs):
        out.append(c_array("int8_t", f"wd_c{i}_w", c.w, str))
        out.append(c_array("int32_t", f"wd_c{i}_b", c.b, str))
        out.append(c_array("float", f"wd_c{i}_m", c.m, f32))
    out.append(c_array("int8_t", "wd_head_w", q.head_w, str))
    out.append(c_array("float", "wd_head_m", q.head_m, f32))
    out.append(c_array("float", "wd_head_b", q.head_b, f32))
    out.append("#endif\n")
    path.write_text("".join(out))


def macs() -> int:
    total, lin = 0, cnn.SIZE
    for cin, cout, k, stride, pool in [(1, 16, 64, 8, 1), (16, 32, 3, 1, 1), (32, 64, 3, 1, 1), (64, 64, 3, 1, 0)]:
        lout = (lin - k) // stride + 1
        total += cout * lout * cin * k
        lin = lout // 2 if pool else lout
    return total + 64 * 10


def main():
    cc = os.environ.get("CC", "gcc")
    arm = os.environ.get("ARM_CC", "arm-none-eabi-gcc")
    W, y, load, _ = build()
    rng = np.random.default_rng(0)
    folds = []
    with tempfile.TemporaryDirectory() as td:
        td = Path(td)
        for hp in range(4):
            ck = torch.load(ROOT / f"models/wdcnn_test{hp}hp.pt")
            m = cnn.WDCNN()
            m.load_state_dict(ck["state"])
            m.eval()
            tr, te = load != hp, load == hp
            x_tr = cnn.prepare(W[tr], ck["scale"]).numpy()
            x_te = cnn.prepare(W[te], ck["scale"]).numpy()
            q = int8.quantise(m, x_tr[rng.choice(len(x_tr), 256, replace=False)])
            write_header(q, FW / "wdcnn_weights.h")

            exe = td / f"wdcnn_host{hp}.exe"
            subprocess.run([cc, *CFLAGS, "-I", str(FW), str(FW / "wdcnn.c"), str(FW / "host_main.c"),
                            "-lm", "-o", str(exe)], check=True)
            inp, outp = td / "x.bin", td / "logits.bin"
            with open(inp, "wb") as f:
                np.int32(len(x_te)).tofile(f)
                x_te.astype(np.float32).tofile(f)
            subprocess.run([str(exe), str(inp), str(outp)], check=True)
            c_logits = np.fromfile(outp, dtype=np.float32).reshape(len(x_te), -1)
            ref = int8.logits(x_te, q)
            p = c_logits.argmax(1)
            with torch.no_grad():
                p_fp32 = m(torch.from_numpy(x_te)).argmax(1).numpy()
            row = {
                "test_load_hp": hp,
                "bit_exact_vs_numpy": bool(np.array_equal(c_logits.view(np.uint32), ref.view(np.uint32))),
                "macro_f1_c_int8": float(f1_score(y[te], p, average="macro")),
                "macro_f1_fp32": float(f1_score(y[te], p_fp32, average="macro")),
                "agrees_with_fp32": float((p == p_fp32).mean()),
            }
            folds.append(row)
            print(row)
            if hp == 0:
                fold0_header = (FW / "wdcnn_weights.h").read_text()

        # Cortex-M4 size build with the fold-0 weights
        (FW / "wdcnn_weights.h").write_text(fold0_header)
        elf = td / "wdcnn_m4.elf"
        subprocess.run([arm, *M4FLAGS, "-I", str(FW), str(FW / "wdcnn.c"), str(FW / "mcu_main.c"),
                        "--specs=nano.specs", "--specs=nosys.specs", "-Wl,--gc-sections", "-lm",
                        "-o", str(elf)], check=True, cwd=td)
        size = subprocess.run([arm.replace("gcc", "size"), "-A", str(elf)], check=True,
                              capture_output=True, text=True).stdout
        sec = {m.group(1): int(m.group(2)) for m in re.finditer(r"^(\.\w+)\s+(\d+)", size, re.M)}
        obj = td / "wdcnn_only.o"
        subprocess.run([arm, *M4FLAGS, "-I", str(FW), "-c", str(FW / "wdcnn.c"), "-o", str(obj)], check=True, cwd=td)
        kern = subprocess.run([arm.replace("gcc", "size"), "-A", str(obj)], check=True,
                              capture_output=True, text=True).stdout
        ksec = {m.group(1): int(m.group(2)) for m in re.finditer(r"^(\.[\w.]+)\s+(\d+)", kern, re.M)}
        su = "".join(p.read_text() for p in td.glob("wdcnn*.su"))
        stack = {m.group(1): int(m.group(2)) for m in re.finditer(r":(\w+)\t(\d+)\t", su)}

    kernel_flash = sum(v for k, v in ksec.items() if k.startswith((".text", ".rodata")))
    kernel_ram = sum(v for k, v in ksec.items() if k.startswith((".bss", ".data")))
    out = {
        "folds": folds,
        "all_bit_exact": all(f["bit_exact_vs_numpy"] for f in folds),
        "macro_f1_c_int8_mean": float(np.mean([f["macro_f1_c_int8"] for f in folds])),
        "macro_f1_fp32_mean": float(np.mean([f["macro_f1_fp32"] for f in folds])),
        "macs_per_window": macs(),
        "cortex_m4": {
            "compiler": subprocess.run([arm, "--version"], capture_output=True, text=True).stdout.splitlines()[0],
            "flags": " ".join(M4FLAGS),
            "kernel_flash_bytes": kernel_flash,
            "kernel_static_ram_bytes": kernel_ram,
            "kernel_stack_bytes": stack,
            "whole_image_sections": sec,
        },
    }
    (ROOT / "results/firmware.json").write_text(json.dumps(out, indent=2))
    print(json.dumps({k: v for k, v in out.items() if k != "folds"}, indent=2))


if __name__ == "__main__":
    if not shutil.which(os.environ.get("CC", "gcc")):
        sys.exit("no host C compiler: set CC")
    main()
